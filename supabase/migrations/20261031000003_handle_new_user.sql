-- Public sign-up runs with email confirmation ON, so supabase.auth.signUp
-- returns no session and a client-side profiles insert fails RLS.
-- Create the patient profile from a security-definer trigger instead.
-- Role is hardcoded to 'patient': signup metadata can never escalate role.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email, '@', 1)),
    'patient'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
